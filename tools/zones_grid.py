#!/usr/bin/env python3
"""Generate traffic-control zones as a regular grid of cells.

Splits the warehouse floor into a grid of about CELL x CELL metre cells,
drops the cells that are mostly obstacle (less than MIN_FREE of their area
free on the navigation map), and writes config/zones.yaml with an empty
edge list. Then run tools/zones_edges.py to connect neighbouring cells and
place their doors.

    python3 tools/zones_grid.py [--cell 2.3] [--ybreaks Y1 Y2 ...]   # inside the sim image

--ybreaks gives the row boundaries explicitly (between the floor's bottom
and top). For this warehouse they follow the shelf rows, so that every
pick station gets its own row:
    --ybreaks -6.75 -4.83 -3.04 -1.24 0.83 2.9 5.4 7.9

Cells are named rRcC (row R from the bottom, column C from the left). A
zone set is a 63-bit mask, so at most 63 cells.
"""
import argparse
import math

import numpy as np
import yaml
from PIL import Image

SHARE = '/ws/src/warehouse_sim/'
FLOOR = (-6.9, -10.1, 6.9, 10.4)   # inside the walls: x_min, y_min, x_max, y_max
MIN_FREE = 0.25


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--cell', type=float, default=2.3, help='target cell size (m)')
    ap.add_argument('--ybreaks', type=float, nargs='*', default=None,
                    help='row boundaries (y, between the floor bottom and top) instead of even rows')
    ap.add_argument('--drop', nargs='*', default=[], help='cells to leave out (e.g. unreachable ones)')
    a = ap.parse_args()
    m = yaml.safe_load(open(SHARE + 'maps/warehouse_nav.yaml'))
    img = np.array(Image.open(SHARE + 'maps/' + m['image']).convert('L'))
    H, W = img.shape
    res, (ox, oy) = m['resolution'], m['origin'][:2]

    x0, y0, x1, y1 = FLOOR
    nx, ny = max(1, round((x1 - x0) / a.cell)), max(1, round((y1 - y0) / a.cell))
    xs = [round(x0 + (x1 - x0) * i / nx, 2) for i in range(nx + 1)]
    ys = [round(y0 + (y1 - y0) * j / ny, 2) for j in range(ny + 1)]
    if a.ybreaks:
        ys = [y0] + sorted(a.ybreaks) + [y1]
        ny = len(ys) - 1

    zones = []
    for r in range(ny):
        for c in range(nx):
            cx0, cx1, cy0, cy1 = xs[c], xs[c + 1], ys[r], ys[r + 1]
            c0, c1 = int((cx0 - ox) / res), int((cx1 - ox) / res)
            r0, r1 = H - 1 - int((cy1 - oy) / res), H - 1 - int((cy0 - oy) / res)
            free = float(np.mean(img[r0:r1, c0:c1] > 250))
            if free >= MIN_FREE and f'r{r + 1}c{c + 1}' not in a.drop:
                zones.append((f'r{r + 1}c{c + 1}', [cx0, cy0, cx1, cy1], free))
    if len(zones) > 63:
        raise SystemExit(f'{len(zones)} cells: more than 63, use a larger --cell')

    with open(SHARE + 'config/zones.yaml', 'w') as f:
        f.write(f'''# Traffic-control zones in the map frame (see PLAN.md, "Traffic control").
# A set of zones is an Integer bitmask: zone k is bit k, in the order below
# (at most 63 zones). rect is [x_min, y_min, x_max, y_max] in metres.
#
# Generated by tools/zones_grid.py --cell {a.cell}{' --ybreaks ' + ' '.join(map(str, a.ybreaks)) if a.ybreaks else ''}{' --drop ' + ' '.join(a.drop) if a.drop else ''}:
# a {nx} x {ny} grid, columns {(x1 - x0) / nx:.2f} m wide, row boundaries at y = {', '.join(map(str, ys))}.
# rRcC = row R from the bottom, column C from the left; cells under
# {MIN_FREE:.0%} free (and those dropped) are left out.
#
# `edges` is written by tools/zones_edges.py from the map: two zones are
# connected when they share a boundary with at least 0.7 m of free passage;
# the two numbers are the door (where robots cross).
zones:
''')
        for name, rect, free in zones:
            f.write(f'  - {{name: {name}, rect: [{rect[0]}, {rect[1]}, {rect[2]}, {rect[3]}]}}   # {free:.0%} free\n')
        f.write('edges: []\n')
    print(f'{len(zones)} cells of {nx * ny} written ({nx} x {ny}, columns {(x1 - x0) / nx:.2f} m, rows at {ys})')


if __name__ == '__main__':
    main()
